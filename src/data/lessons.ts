/** كل الكلمات في التطبيق، مسطّحة مع معرّف الدرس. */
export const ALL_WORDS: (Word & { lessonId: string })[] = LESSONS.flatMap((lesson) =>
  lesson.words.map((word) => ({ ...word, lessonId: lesson.id }))
);

export const TOTAL_WORDS = ALL_WORDS.length;

export function getLesson(id: string): Lesson | undefined {
  return LESSONS.find((lesson) => lesson.id === id);
}

export function getWord(id: string): (Word & { lessonId: string }) | undefined {
  return ALL_WORDS.find((word) => word.id === id);
}

export function lessonsByLevel(level: Level): Lesson[] {
  return LESSONS.filter((lesson) => lesson.level === level);
}
